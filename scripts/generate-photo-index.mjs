/**
 * Regenerates src/photos/index.ts from whatever is in src/photos/files.
 *
 *   node scripts/generate-photo-index.mjs
 *
 * Each file is statically imported so Next.js supplies intrinsic width, height and a
 * blurDataURL at build time — that's why the masters live in src/ rather than public/.
 * Editorial metadata (alt text, category, series, tags) is NOT generated: it lives in
 * the hand-authored src/photos/metadata.ts and is joined in at module load, so re-running
 * this never clobbers it.
 */
import { readdirSync, writeFileSync } from "node:fs";

const files = readdirSync("src/photos/files")
  .filter((f) => /\.(webp|jpe?g|png|avif)$/i.test(f))
  .sort();

const ident = (slug) => "p_" + slug.replace(/[^a-z0-9]/gi, "_");

const out = `// GENERATED by scripts/generate-photo-index.mjs — do not edit by hand.
// Editorial metadata lives in ./metadata.ts and is safe to edit.

import type { StaticImageData } from "next/image";
import { photoMetadata, type PhotoCategory, type PhotoMeta, type PhotoTag } from "./metadata";

export type { PhotoCategory, PhotoTag };

${files.map((f) => `import ${ident(f.replace(/\.[^.]+$/, ""))} from "./files/${f}";`).join("\n")}

export type Photo = PhotoMeta & {
  /** Stable id, derived from the original filename. */
  slug: string;
  src: StaticImageData;
  width: number;
  height: number;
  orientation: "portrait" | "landscape" | "square";
};

const files_: ReadonlyArray<[string, StaticImageData]> = [
${files
  .map((f) => `  ["${f.replace(/\.[^.]+$/, "")}", ${ident(f.replace(/\.[^.]+$/, ""))}],`)
  .join("\n")}
];

export const photos: readonly Photo[] = files_.map(([slug, src]) => {
  const meta = photoMetadata[slug];
  if (!meta) {
    throw new Error(
      \`No metadata for photo "\${slug}". Add an entry to src/photos/metadata.ts.\`,
    );
  }
  return {
    ...meta,
    slug,
    src,
    width: src.width,
    height: src.height,
    orientation:
      src.height > src.width ? "portrait" : src.width > src.height ? "landscape" : "square",
  };
});

const bySlug = new Map(photos.map((p) => [p.slug, p]));

/** Look up one photo. Throws on an unknown slug so typos fail at render, not silently. */
export function photo(slug: string): Photo {
  const found = bySlug.get(slug);
  if (!found) throw new Error(\`Unknown photo "\${slug}".\`);
  return found;
}

export const byCategory = (...c: PhotoCategory[]) =>
  photos.filter((p) => c.includes(p.category));

export const byTag = (...t: PhotoTag[]) =>
  photos.filter((p) => t.some((tag) => p.tags?.includes(tag)));

export const bySeries = (series: string) =>
  photos.filter((p) => p.series === series);

export const seriesNames: readonly string[] = [
  ...new Set(photos.flatMap((p) => (p.series ? [p.series] : []))),
].sort();

/**
 * PLACE → PERSON → DETAIL → WORK, repeating. Draws from the pools in order so a run of
 * images alternates instead of clumping — the editorial rhythm in docs/DIRECTION.md.
 * Falls back to any remaining photo once a pool runs dry.
 */
export function editorialRhythm(count: number, from: readonly Photo[] = photos): Photo[] {
  const order: PhotoCategory[] = ["place", "person", "detail", "work"];
  const pools = new Map(order.map((c) => [c, from.filter((p) => p.category === c)]));
  const cursors = new Map(order.map((c) => [c, 0]));
  const used = new Set<string>();
  const out: Photo[] = [];

  for (let i = 0; out.length < count && i < count * order.length; i++) {
    const c = order[i % order.length];
    const pool = pools.get(c)!;
    const cursor = cursors.get(c)!;
    if (cursor < pool.length) {
      cursors.set(c, cursor + 1);
      out.push(pool[cursor]);
      used.add(pool[cursor].slug);
    }
  }
  for (const p of from) {
    if (out.length >= count) break;
    if (!used.has(p.slug)) out.push(p);
  }
  return out.slice(0, count);
}
`;

writeFileSync("src/photos/index.ts", out);
console.log(`${files.length} photos indexed`);
