/**
 * Regenerates the generated brand modules from the SVGs in public/brand.
 * Run after adding or replacing any logo or illustration asset:
 *
 *   node scripts/generate-logo-paths.mjs
 *
 * Emits:
 *   src/components/brand/logo-paths.ts   inline path data for the small lockups
 *   src/components/brand/art-manifest.ts names + aspect ratios for mask-rendered art
 *
 * Only the small lockups are inlined. The badge and the illustrations stay static
 * files (the badge alone is ~100 KB of charcoal texture) and are rendered through a
 * CSS mask instead, which keeps them cached, out of the HTML, and recolorable.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";

const MARKS = {
  lockup: "public/brand/logos/lockup-black.svg",
  wordmark: "public/brand/logos/wordmark-black.svg",
  monogram: "public/brand/logos/monogram-black.svg",
};

const entries = Object.entries(MARKS).map(([name, file]) => {
  const svg = readFileSync(file, "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`no viewBox in ${file}`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`no paths in ${file}`);
  const [, , w, h] = viewBox.split(/\s+/).map(Number);
  return { name, viewBox, paths, ratio: +(w / h).toFixed(4) };
});

const out = `// GENERATED by scripts/generate-logo-paths.mjs — do not edit by hand.
// Source: public/brand/logos/*-black.svg

export type LogoMark = ${entries.map((e) => `"${e.name}"`).join(" | ")};

export const logoPaths: Record<
  LogoMark,
  { viewBox: string; paths: readonly string[]; ratio: number }
> = {
${entries
  .map(
    (e) => `  ${e.name}: {
    viewBox: "${e.viewBox}",
    ratio: ${e.ratio},
    paths: [
${e.paths.map((d) => `      "${d}",`).join("\n")}
    ],
  },`,
  )
  .join("\n")}
};
`;

writeFileSync("src/components/brand/logo-paths.ts", out);

// --- mask-rendered art: illustrations + the badge -------------------------------

function ratioOf(file) {
  const viewBox = readFileSync(file, "utf8").match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`no viewBox in ${file}`);
  const [, , w, h] = viewBox.split(/\s+/).map(Number);
  return +(w / h).toFixed(4);
}

const illustrations = readdirSync("public/brand/illustrations")
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((f) => ({
    name: f.replace(/\.svg$/, ""),
    src: `/brand/illustrations/${f}`,
    ratio: ratioOf(`public/brand/illustrations/${f}`),
  }));

const art = [
  ...illustrations,
  { name: "badge", src: "/brand/logos/badge-black.svg", ratio: ratioOf("public/brand/logos/badge-black.svg") },
];

const artOut = `// GENERATED by scripts/generate-logo-paths.mjs — do not edit by hand.
// Source: public/brand/illustrations/*.svg and public/brand/logos/badge-black.svg
//
// These are rendered as CSS masks tinted with \`currentColor\`, so the single black
// source file serves every colorway. The \`src\` is the mask URL; \`ratio\` is the
// asset's intrinsic width/height, used to reserve layout space.

export type ArtName = ${art.map((a) => `"${a.name}"`).join(" | ")};

export const art: Record<ArtName, { src: string; ratio: number }> = {
${art.map((a) => `  "${a.name}": { src: "${a.src}", ratio: ${a.ratio} },`).join("\n")}
};

export const illustrationNames = [
${illustrations.map((a) => `  "${a.name}",`).join("\n")}
] as const satisfies readonly ArtName[];
`;

writeFileSync("src/components/brand/art-manifest.ts", artOut);

console.log(
  [
    ...entries.map((e) => `inline ${e.name}: ${e.paths.length} path(s), ratio ${e.ratio}`),
    ...art.map((a) => `mask   ${a.name}: ratio ${a.ratio}`),
  ].join("\n"),
);
